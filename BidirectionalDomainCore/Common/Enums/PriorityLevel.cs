namespace Bidirectional.DomainCore.Common.Enums;

/// <summary>
/// Specifies the priority level for a task or operation.
/// </summary>
public enum PriorityLevel
{
    /// <summary>
    /// Indicates no priority.
    /// </summary>
    None = 0,
    /// <summary>
    /// Indicates a low priority.
    /// </summary>
    Low = 1,
    /// <summary>
    /// Indicates a medium priority.
    /// </summary>
    Medium = 2,
    /// <summary>
    /// Indicates a high priority.
    /// </summary>
    High = 3,
}
